/** 동의 항목. 만 14세 확인은 약관 전문이 없어 따로 둔다(ConsentChecks.age14). */
export type ConsentKey = "privacy" | "medication" | "pharmacyAd" | "cresotyAd";

/** 약관 동의 화면의 체크 상태. */
export type ConsentChecks = Record<ConsentKey, boolean> & { age14: boolean };

/** 약관 동의 화면은 매번 모두 해제된 상태로 시작한다. */
export const EMPTY_CHECKS: ConsentChecks = {
  age14: false,
  privacy: false,
  medication: false,
  pharmacyAd: false,
  cresotyAd: false,
};

/** 모두 체크됐는지 (전체 동의 표시). */
export function isAllChecked(c: ConsentChecks): boolean {
  return c.age14 && c.privacy && c.medication && c.pharmacyAd && c.cresotyAd;
}

/** [동의] 를 누를 수 있는지 — 만 14세 확인과 필수 항목. */
export function canAgree(c: ConsentChecks): boolean {
  return c.age14 && c.privacy;
}

/** 오늘 날짜 YYYY-MM-DD (단말 현지 시각) — 동의 처리 완료 화면의 의사표시일. */
export function todayYmd(now: Date = new Date()): string {
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}

