/** 굵은 이름표 + 본문 한 줄. label 만 있으면 이름표 한 줄, text 만 있으면 본문 한 줄. */
export type TermsLine = { label?: string; text?: string };

export type TermsBlock =
  | { kind: "p"; text: string }
  | { kind: "fields"; lines: TermsLine[] }
  /** 동의 상자 — 눌러서 체크하면 약관 동의 화면의 같은 항목도 체크된다. */
